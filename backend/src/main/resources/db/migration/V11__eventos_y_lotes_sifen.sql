-- Guía de Pruebas e-Kuatia (DNIT), grupo 2: eventos del emisor (siRecepEvento, Manual Técnico v150
-- 9.5 y 11.5.1) y envío asíncrono por lote (siRecepLoteDE / siResultLoteDE, 9.2 y 9.3).

-- Cada evento enviado al SIFEN, con su resultado. El id numérico es el atributo Id del <rEve>
-- (GDE003, N 1-10), así que tiene que existir antes de firmar.
create table evento_sifen (
    id_evento       bigint generated by default as identity primary key,
    tipo            varchar(20) not null,          -- CANCELACION | INUTILIZACION
    factura_id      uuid not null references factura_electronica(id_factura),
    motivo          varchar(500) not null,
    fecha           timestamp not null default now(),
    ambiente        varchar(20),
    estado          varchar(20) not null,          -- PENDIENTE | APROBADO | RECHAZADO | SIN_CONFIRMAR
    codigo          varchar(20),
    mensaje         text,
    protocolo       varchar(20),                   -- dProtAut del SIFEN
    xml_firmado     text,
    usuario_id      uuid references usuario(id_usuario)
);

create index idx_evento_sifen_factura on evento_sifen(factura_id);

-- Un lote de hasta 50 DE del mismo tipo enviado por el WS asíncrono.
create table lote_sifen (
    id_lote          uuid primary key,
    tipo_doc         varchar(5) not null,
    numero_lote      varchar(20),                  -- dProtConsLote
    estado           varchar(20) not null,         -- RECIBIDO | NO_RECIBIDO | SIN_CONFIRMAR | CONCLUIDO
    codigo           varchar(20),
    mensaje          text,
    fecha_envio      timestamp not null default now(),
    fecha_consulta   timestamp,
    cantidad         int not null,
    ambiente         varchar(20),
    usuario_id       uuid references usuario(id_usuario)
);

alter table factura_electronica add column lote_id uuid references lote_sifen(id_lote);
create index idx_factura_lote on factura_electronica(lote_id);
